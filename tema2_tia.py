plot_confusion_matrix(test_conf_matrix, class_mapping)

test_report = classification_report(y_test, y_test_pred_knn, target_names=class_mapping.values())
print("Raport de clasificare pentru KNN pe setul de testare:\n", test_report)

# Salvarea rezultatelor pentru testare
save_results('knn', y_test, y_test_pred_knn, class_mapping)

