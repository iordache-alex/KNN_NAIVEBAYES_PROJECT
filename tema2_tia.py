# Verificare dimensiuni, se adauga totalul la 128 ceea ce e adevarat.

# Clasificator KNN
knn_classifier = KNeighborsClassifier(n_neighbors=3)
knn_classifier.fit(X_train, y_train)

# Antrenare
y_train_pred = knn_classifier.predict(X_train)
train_accuracy = accuracy_score(y_train, y_train_pred)
print(f"Accuratețe pe setul de antrenare: {train_accuracy}")

train_conf_matrix = confusion_matrix(y_train, y_train_pred)
print("Matricea de confuzie pentru KNN pe setul de antrenare:\n", train_conf_matrix)

# Vizualizare matrice de confuzie pentru antrenare
plot_confusion_matrix(train_conf_matrix, class_mapping)

train_report = classification_report(y_train, y_train_pred, target_names=class_mapping.values())
print("Raport de clasificare pentru KNN pe setul de antrenare:\n", train_report)

# Validare
y_val_pred = knn_classifier.predict(X_val)
val_accuracy = accuracy_score(y_val, y_val_pred)
print(f"Accuratețe pe setul de validare: {val_accuracy}")

val_conf_matrix = confusion_matrix(y_val, y_val_pred)
print("Matricea de confuzie pentru KNN pe setul de validare:\n", val_conf_matrix)

# Vizualizare matrice de confuzie pentru validare
plot_confusion_matrix(val_conf_matrix, class_mapping)

val_report = classification_report(y_val, y_val_pred, target_names=class_mapping.values())
print("Raport de clasificare pentru KNN pe setul de validare:\n", val_report)

# Testare
y_test_pred_knn = knn_classifier.predict(X_test)
test_accuracy = accuracy_score(y_test, y_test_pred_knn)
print(f"Accuratețe pe setul de testare: {test_accuracy}")

test_conf_matrix = confusion_matrix(y_test, y_test_pred_knn)
print("Matricea de confuzie pentru KNN pe setul de testare:\n", test_conf_matrix)

